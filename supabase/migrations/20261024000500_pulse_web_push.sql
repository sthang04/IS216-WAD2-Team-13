-- =====================================================================
-- Pulse — 5  Web Push (browser notifications). Additive, safe to re-run.
-- Every notification row for a member who has turned on browser alerts
-- is marked push_status = 'PENDING'; the send-web-push Edge Function
-- delivers it and marks it SENT / FAILED.
-- =====================================================================
create table if not exists push_subscriptions (
  id          bigint generated by default as identity primary key,
  member_id   bigint not null references members(id) on delete cascade,
  endpoint    text not null unique,
  p256dh      text not null,
  auth        text not null,
  user_agent  text,
  created_at  timestamptz not null default now()
);
alter table push_subscriptions enable row level security;
revoke all on push_subscriptions from anon, authenticated;

alter table notifications add column if not exists push_status text not null default 'NOT_REQUIRED';

-- Marks a new notification as waiting to be sent as a phone push
create or replace function pulse_mark_push_pending() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.recipient_member_id is not null
     and exists (select 1 from push_subscriptions where member_id = new.recipient_member_id) then
    new.push_status := 'PENDING';
  end if;
  return new;
end $$;

drop trigger if exists pulse_notifications_push on notifications;
-- Runs pulse_mark_push_pending for each new notification
create trigger pulse_notifications_push
  before insert on notifications
  for each row execute function pulse_mark_push_pending();

-- Saves this browser so it can receive push notifications
create or replace function rpc_save_push_subscription(p_endpoint text, p_p256dh text, p_auth text,
                                                      p_user_agent text default null, p_demo_member_id bigint default null)
returns jsonb
language plpgsql security definer set search_path = public as $$
declare v_member bigint := current_member_id(p_demo_member_id);
begin
  if v_member is null then raise exception 'Sign in to turn on browser alerts'; end if;
  insert into push_subscriptions (member_id, endpoint, p256dh, auth, user_agent)
  values (v_member, p_endpoint, p_p256dh, p_auth, p_user_agent)
  on conflict (endpoint) do update
     set member_id = excluded.member_id, p256dh = excluded.p256dh, auth = excluded.auth, user_agent = excluded.user_agent;
  return jsonb_build_object('saved', true);
end $$;

-- Stops push notifications for this browser
create or replace function rpc_delete_push_subscription(p_endpoint text, p_demo_member_id bigint default null)
returns void
language sql security definer set search_path = public as $$
  delete from push_subscriptions where endpoint = p_endpoint and member_id = current_member_id(p_demo_member_id)
$$;

revoke execute on function pulse_mark_push_pending() from public, anon, authenticated;
grant execute on function rpc_save_push_subscription(text, text, text, text, bigint), rpc_delete_push_subscription(text, bigint)
  to anon, authenticated;
