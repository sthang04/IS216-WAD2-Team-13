async function boot(page,mode='manual',multiple=false){
 await page.route('https://**',r=>r.abort())
 await page.route('**/src/services/simulationDataService.js*',r=>r.fulfill({contentType:'application/javascript',body:
  "import {campusConnectFixture,campusConnectMultiEventFixture} from '/e2e-simulator/fixtures/campusConnect.js';export async function loadSimulationData(){return "+(multiple?'campusConnectMultiEventFixture()':"campusConnectFixture('"+mode+"')")+"}"}))
 await page.goto('/e2e-simulator/harness.html')
 await page.getByLabel('Unavailable from (Singapore)',{exact:true}).selectOption('2026-11-02T10:00')
 await page.getByLabel('Unavailable until (Singapore)',{exact:true}).selectOption('2026-11-02T10:30')
 await page.getByRole('button',{name:'Run simulation (1)',exact:true}).click()
 await openTimeline(page)
}
