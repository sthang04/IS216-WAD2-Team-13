test('ranked plan selection changes comparison, preparation and recovery inspection; playback shares heatmap time',async({page})=>{
 await page.clock.install()
 await boot(page)
 const cards=page.locator('.recovery-choice')
 expect(await cards.count()).toBeGreaterThan(1)
 const ids=[]
 for(const card of [cards.nth(0),cards.nth(1)]){
  const id=await card.getAttribute('data-plan-id');ids.push(id)
  await card.getByRole('button',{name:'Select this plan',exact:true}).click()
  await expect(card).toHaveClass(/is-selected/)
  await expect(page.getByRole('region',{name:'Persisted recovery workflow',exact:true})).toHaveAttribute('data-selected-recovery',id)
  const title=await card.getAttribute('data-plan-title')
  await expect(page.locator('#simulator-comparison')).toContainText(title.trim())
  await page.getByRole('button',{name:'Preview selected recovery',exact:true}).click()
  await expect(page.getByLabel('Visualization proposal')).toContainText(title.trim())
 }
 expect(ids[0]).not.toBe(ids[1])
 const impact=page.getByRole('region',{name:'Event impact workspace',exact:true})
 await impact.getByRole('button',{name:'Disruption impact',exact:true}).click()
 const slider=impact.getByRole('slider',{name:'Timeline playback time',exact:true})
 await slider.fill('15')
 await expect(slider).toHaveValue('15')
 await impact.getByRole('button',{name:'Play timeline',exact:true}).click()
 await expect.poll(async()=>Number(await slider.inputValue())).toBeGreaterThan(15)
 await impact.getByRole('button',{name:'Pause timeline',exact:true}).click()
 const stopped=await slider.inputValue();await page.clock.runFor(400);await expect(slider).toHaveValue(stopped)
 if(await impact.getByRole('button',{name:'Show heatmap',exact:true}).isVisible())await impact.getByRole('button',{name:'Show heatmap',exact:true}).click();await openFacilityHeatmap(page)
 await impact.locator('.sim-heat-cell').last().click()
 await expect(impact.locator('.sim-heat-cell.current')).toHaveCount(1)
 await expect(impact.locator('.sim-inspection')).toContainText('Fixture Original Room')
 await impact.getByRole('button',{name:'Replay cascade',exact:true}).click()
 await expect(impact.locator('.sim-graph-node.direct').first()).toHaveCSS('animation-name',/^impact-cascade/)
 await page.emulateMedia({reducedMotion:'reduce'})
 await expect(impact.locator('.sim-graph-node.direct').first()).toHaveCSS('animation-name','none')
})


