test('mobile exploration scrolls both axes and supports keyboard with reduced motion',async({page})=>{
 await page.setViewportSize({width:390,height:844})
 await page.emulateMedia({reducedMotion:'reduce'})
 await boot(page)
 const map=page.locator('.village-scroll')
 const dimensions=await map.evaluate(el=>({x:el.scrollWidth>el.clientWidth,y:el.scrollHeight>el.clientHeight}))
 expect(dimensions).toEqual({x:true,y:true})
 await map.evaluate(el=>{el.scrollLeft=200;el.scrollTop=120})
 expect(await map.evaluate(el=>el.scrollLeft)).toBeGreaterThan(0)
 expect(await map.evaluate(el=>el.scrollTop)).toBeGreaterThan(0)
 await page.getByRole('button',{name:'Fit whole map',exact:true}).click()
 const node=page.locator('.village-node').first()
 await node.focus();await page.keyboard.press('Enter')
 await expect(node).toHaveAttribute('aria-pressed','true')
 await expect(node).toHaveCSS('animation-name','none')
 await expect(page.locator('.sim-inspection')).toContainText('Fixture activity 1')
 await page.getByRole('button',{name:'Explore map',exact:true}).click()
 await expect(map).not.toHaveClass(/fit/)
})
